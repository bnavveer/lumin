export const DEMO_TEMPLATES = ['interview_scheduled', 'documents_requested', 'approved'] as const;
export type DemoTemplate = (typeof DEMO_TEMPLATES)[number];

const NOTICE = '[DEMO SIMULATION: this message was generated by Aid to demonstrate email handling. It is not from the real LA County DPSS.]';

const fmtDate = (d: Date): string =>
  d.toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'America/Los_Angeles' });

export function demoEmail(t: DemoTemplate, firstName = 'Applicant', now = new Date()): { subject: string; text: string } {
  const plus = (days: number): Date => new Date(now.getTime() + days * 86_400_000);
  const sign = '\nLos Angeles County Department of Public Social Services\nCalFresh Eligibility Unit\n\n' + NOTICE;
  switch (t) {
    case 'interview_scheduled':
      return {
        subject: 'DPSS: Your CalFresh interview has been scheduled (DEMO)',
        text: `Dear ${firstName},\n\nYour CalFresh eligibility interview is scheduled on ${fmtDate(plus(2))} at 9:00 AM. A county worker will call you at the phone number on your application. If you miss the call, please call us back the same day.\n${sign}`,
      };
    case 'documents_requested':
      return {
        subject: 'DPSS: Documents needed for your CalFresh application (DEMO)',
        text: `Dear ${firstName},\n\nTo continue processing your CalFresh application, please provide the following by ${fmtDate(plus(10))}:\n- Pay stubs for the last 30 days\n- Proof of address (lease or utility bill)\n- Photo ID\n\nYou can upload documents at benefitscal.com or bring them to your local office.\n${sign}`,
      };
    case 'approved':
      return {
        subject: 'DPSS: Your CalFresh application has been approved (DEMO)',
        text: `Dear ${firstName},\n\nGood news. Your CalFresh application has been approved. Your EBT card will arrive in the mail within 7 days and benefits begin on ${fmtDate(plus(1))}.\n${sign}`,
      };
  }
}
